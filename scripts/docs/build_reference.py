"""Generate configuration and source-symbol indexes without importing ICESEE.

Run from a source checkout with ``python scripts/docs/build_reference.py``.
``--source-root`` and ``--output-dir`` allow read-only source snapshots to be
documented into a separate staging tree. Only Markdown indexes are written.
"""
from __future__ import annotations

import argparse
import ast
from pathlib import Path


def escaped(value: str) -> str:
    return value.replace("|", "&#124;").replace("\n", " ").replace("`", "'")


def source_link(relative: Path, line: int | None = None) -> str:
    suffix = f"#L{line}" if line is not None else ""
    return f"../../{relative.as_posix()}{suffix}"


def configuration_index(root: Path) -> str:
    relative = Path("config/_utility_imports.py")
    tree = ast.parse((root / relative).read_text())
    entries: dict[str, list[tuple[int, str]]] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Attribute):
            continue
        if node.func.attr != "get" or not isinstance(node.func.value, ast.Name):
            continue
        if node.func.value.id != "_enkf_section" or not node.args:
            continue
        key = node.args[0]
        if not isinstance(key, ast.Constant) or not isinstance(key.value, str):
            continue
        default = ast.unparse(node.args[1]) if len(node.args) > 1 else "None"
        entries.setdefault(key.value, []).append((node.lineno, default))
    lines = [
        "# Configuration loader key index", "",
        "Generated by `scripts/docs/build_reference.py` using Python AST inspection; no application code is imported. These are absent-key fallback expressions in the loader, not validated universal settings. Raw YAML flattening and application setup can override them. Read the [configuration guide](configuration.md) before using this table. Required lookups such as `vec_inputs`, application-only keys, and runtime-only keys are not exhaustive here.", "",
        f"Found {len(entries)} distinct `_enkf_section.get` keys. Repeated lookups are retained when their fallback expressions differ. Source links point to the inspected loader lines; regenerate after source changes.", "",
        "| Key | Fallback expression in source | Source line |",
        "|---|---|---|",
    ]
    for key in sorted(entries):
        seen: set[str] = set()
        for line, default in sorted(entries[key]):
            if default in seen:
                continue
            seen.add(default)
            lines.append(f"| `{key}` | `{escaped(default)}` | [L{line}]({source_link(relative, line)}) |")
    return "\n".join(lines) + "\n"


def included(path: Path, root: Path) -> bool:
    rel = path.relative_to(root)
    if any(part in {"__pycache__", ".ipynb_checkpoints", "tests"} for part in rel.parts):
        return False
    if rel.parts[0] in {"src", "config"}:
        return True
    if rel == Path("applications/supported_models.py"):
        return True
    # Include integration boundaries and entrypoints, not vendored model helpers.
    return any(token in path.stem for token in ("enkf", "native", "mode3", "distributed_adapter", "run_da"))


def function_signature(node: ast.FunctionDef | ast.AsyncFunctionDef) -> str:
    prefix = "async " if isinstance(node, ast.AsyncFunctionDef) else ""
    returns = " -> " + ast.unparse(node.returns) if node.returns else ""
    return f"{prefix}{node.name}({ast.unparse(node.args)}){returns}"


def api_index(root: Path) -> str:
    lines = [
        "# Python module and API index", "",
        "Generated by `scripts/docs/build_reference.py` without importing model or configuration modules. This index covers core/configuration Python files and application integration boundaries/entrypoints, excluding tests and vendored model helper trees. It lists declarations and source locations; a declaration alone does not establish active runtime use or a validated capability. Start with the [active architecture map](architecture.md#code-map). Historical duplicate modules remain listed because they exist in the tree.", "",
        "Signatures retain the source's argument/default annotations. Methods are grouped under their class; private module functions are included because they often own important runtime policy. Existing docstrings and design comments can lag code, so verify the selected runner and tests for behavioral claims.", "",
    ]
    modules = 0
    symbols = 0
    for group in ("config", "src", "applications"):
        lines.extend([f"## {group}", ""])
        for path in sorted((root / group).rglob("*.py")):
            if not included(path, root):
                continue
            relative = path.relative_to(root)
            try:
                tree = ast.parse(path.read_text(encoding="utf-8"))
            except (SyntaxError, UnicodeError) as exc:
                raise RuntimeError(f"Cannot index {relative}: {exc}") from exc
            nodes = [n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))]
            modules += 1
            lines.extend([f"### {relative.as_posix()}", "", f"[Source]({source_link(relative)})", ""])
            if not nodes:
                lines.extend(["No top-level function/class declarations; this module supplies imports, constants, or import-time setup.", ""])
                continue
            for node in nodes:
                symbols += 1
                if isinstance(node, ast.ClassDef):
                    bases = ", ".join(ast.unparse(base) for base in node.bases)
                    label = f"class {node.name}" + (f"({bases})" if bases else "")
                    lines.append(f"- [{escaped(label)}]({source_link(relative, node.lineno)})")
                    for method in node.body:
                        if not isinstance(method, (ast.FunctionDef, ast.AsyncFunctionDef)):
                            continue
                        symbols += 1
                        signature = escaped(function_signature(method))
                        lines.append(f"  - `{signature}` ([L{method.lineno}]({source_link(relative, method.lineno)}))")
                else:
                    signature = escaped(function_signature(node))
                    lines.append(f"- `{signature}` ([L{node.lineno}]({source_link(relative, node.lineno)}))")
            lines.append("")
    lines[2] += f" Indexed {modules} modules and {symbols} function/class/method declarations."
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--output-dir", type=Path)
    args = parser.parse_args()
    root = args.source_root.resolve()
    if not (root / "config/_utility_imports.py").is_file():
        parser.error("source root must contain config/_utility_imports.py")
    output = args.output_dir or root / "docs/handbook"
    output.mkdir(parents=True, exist_ok=True)
    for filename, content in (
        ("configuration-key-index.md", configuration_index(root)),
        ("api-reference.md", api_index(root)),
    ):
        (output / filename).write_text(content, encoding="utf-8")
        print(f"Wrote {output / filename}")


if __name__ == "__main__":
    main()
